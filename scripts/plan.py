# Task generation from scan.json
# ---------------------------------------------------------------------------


def generate_tasks(
    scan_file: Path, out_dir: Path, limit: int = 0, resume: bool = False
):
    with open(scan_file, encoding="utf-8") as f:
        data = json.load(f)

    target = data.get("target", str(scan_file.parent))
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / "tasks.json"

    tasks = None
    if resume and out_file.exists():
        with open(out_file, encoding="utf-8") as f:
            try:
                tasks = json.load(f)
                emit_progress(
                    "DocumentOrganizer",
                    "PLAN",
                    f"Resumed: loaded {len(tasks.get('rename', []))} existing rename tasks.",
                )
            except json.JSONDecodeError:
                pass

    if tasks is None:
        tasks = {
            "target": target,
            "job_dir": str(out_dir),
            "zones": [
                {"id": "MERGE_ZONE", "name": "Auto Merge", "path": target, "moves": []}
            ],
            "dedup": [],
            "rename": [],
        }

    # Always rebuild dedup and merge candidates from the latest scan
    tasks["dedup"] = []
    if not tasks.get("zones"):
        tasks["zones"] = [
            {"id": "MERGE_ZONE", "name": "Auto Merge", "path": target, "moves": []}
        ]
    tasks["zones"][0]["moves"] = []

    # Process Duplicates
    for dup in data.get("duplicates", []):
        paths = dup.get("paths", [])
        if len(paths) > 1:
            tasks["dedup"].append(
                {
                    "hash": dup.get("hash", ""),
                    "keeper": paths[0],
                    "duplicates": paths[1:],
                }
            )

    # Process Merge Candidates
    for merge in data.get("merge_candidates", []):
        folders = merge.get("folders", [])
        if len(folders) >= 2:
            tasks["zones"][0]["moves"].append({"src": folders[1], "dest": folders[0]})

    # Process Content Summaries for Renaming & Routing
    content_summaries = data.get("content_summaries", {})
    if content_summaries and HAS_OLLAMA:
        existing_folders = _discover_existing_folders(target)

        # Load/discover project registry
        registry = load_registry()
        target_path = Path(target)
        for parent in [target_path] + list(target_path.parents):
            if parent.name.startswith("1_") or parent.name == "1_PRIVATE":
                registry = discover_projects(parent, registry)
                break

        pp = resolve_project(target_path, registry)
        if not pp:
            m = re.match(r"^(\d{2})_", target_path.name)
            pp = m.group(1) if m else "99"

        today = datetime.datetime.now().strftime("%Y%m%d")
        project_name = registry.get("projects", {}).get(pp, {}).get("name", "UNKNOWN")
        emit_progress(
            "DocumentOrganizer", "PLAN", f"Project mapping: {pp} ({project_name})"
        )

        from jd_registry import scan_highest_sequence

        highest = scan_highest_sequence(target_path, pp)
        registry.setdefault("sequences", {})[pp] = highest
        emit_progress(
            "DocumentOrganizer",
            "PLAN",
            f"Highest existing sequence for {pp}: {highest}",
        )

        existing_renames = {r["src"] for r in tasks.get("rename", [])}

        actionable = {
            k: v
            for k, v in content_summaries.items()
            if v and not _is_organizer_artifact(k) and k not in existing_renames
        }
        if limit > 0:
            actionable = dict(list(actionable.items())[:limit])

        for filepath in content_summaries:
            if _is_organizer_artifact(filepath):
                tasks["rename"].append(
                    {
                        "src": filepath,
                        "dest_folder": "99_SYSTEM",
                        "dest_name": Path(filepath).name,
                    }
                )

        # --- Phase 3.1: Atomic Extraction & Embeddings ---
        total_files = len(actionable)
        atomic_summaries = {}
        embeddings = {}
        emit_progress(
            "DocumentOrganizer",
            "PLAN",
            "Generating Atomic Summaries & Embeddings",
            progress=f"0/{total_files}",
        )

        def process_file(filepath, content):
            existing_id = extract_id(Path(filepath).name)
            if existing_id:
                return filepath, None, None
            summary = generate_atomic_summary(content)
            emb = compute_embedding(summary)
            return filepath, summary, emb

        with concurrent.futures.ThreadPoolExecutor(max_workers=4) as executor:
            future_to_filepath = {
                executor.submit(process_file, fp, content): fp
                for fp, content in actionable.items()
            }

            completed = 0
            for future in concurrent.futures.as_completed(future_to_filepath):
                filepath = future_to_filepath[future]
                try:
                    fp, summary, emb = future.result()
                    if summary is not None and emb is not None:
                        atomic_summaries[fp] = summary
                        embeddings[fp] = emb
                except Exception as exc:
                    emit_progress(
                        "DocumentOrganizer",
                        "PLAN",
                        f"Error extracting {filepath}: {exc}",
                        level="ERROR",
                    )

                completed += 1
                if completed % 10 == 0 or completed == total_files:
                    emit_progress(
                        "DocumentOrganizer",
                        "PLAN",
                        "Extracting concepts",
                        progress=f"{completed}/{total_files}",
                    )

        # --- Phase 3.2: Semantic Clustering ---
        emit_progress(
            "DocumentOrganizer", "PLAN", "Clustering semantically similar files"
        )
        clusters = cluster_files(embeddings, threshold=0.75)
        emit_progress(
            "DocumentOrganizer", "PLAN", f"Formed {len(clusters)} semantic clusters"
        )

        # --- Phase 3.3: Batch Routing ---
        for c_idx, cluster in enumerate(clusters):
            emit_progress(
                "DocumentOrganizer",
                "PLAN",
                f"Routing Cluster {c_idx + 1}/{len(clusters)} ({len(cluster)} files)",
            )

            cluster_summaries = [atomic_summaries[fp] for fp in cluster]
            routing_suggestion = generate_cluster_routing_suggestion(
                cluster_summaries, existing_folders
            )

            cluster_folder = routing_suggestion.get("suggested_folder", "99_SYSTEM")
            cluster_tags = routing_suggestion.get("tags", [])

            # BATCH RENAME
            batch_titles = generate_batch_title_suggestions(cluster, atomic_summaries)

            for filepath in cluster:
                title = batch_titles.get(filepath, _clean_title(Path(filepath).stem))
                sss = next_sequence(registry, pp)
                ext = Path(filepath).suffix
                dest_name = format_filename(pp, sss, today, title, ext, cluster_tags)
                tasks["rename"].append(
                    {
                        "src": filepath,
                        "dest_folder": cluster_folder,
                        "dest_name": dest_name,
                        "jd_id": f"{pp}.{sss:03d}",
                        "tags": cluster_tags,
                        "atomic_summary": atomic_summaries[
                            filepath
                        ],  # Add summary for readme generation
                    }
                )

        save_registry(registry)
        emit_progress(
            "DocumentOrganizer",
            "PLAN",
            f"Registry saved. Next sequence for {pp}: {registry['sequences'].get(pp, 0)}",
        )

    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(tasks, f, indent=2, ensure_ascii=False)


def generate_rename_suggestion(file_path: str, content: str = "") -> dict:
    """Generate a semantic rename and folder suggestion for a file."""
    try:
        from project_router import ProjectRouter

        p = Path(file_path)
        router = ProjectRouter()
        route = router.resolve_destination(
            filename=p.name, content_hint=content[:1000] if content else ""
        )
        if route:
            return {
                "suggested_folder": str(route.relative_zone_path),
                "suggested_filename": route.standardized_filename,
            }
        return {
            "suggested_folder": "00_INBOX",
            "suggested_filename": router.standardize_filename(p.name),
        }
    except Exception:
        p = Path(file_path)
        return {
            "suggested_folder": "00_INBOX",
            "suggested_filename": p.name,
        }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--scan", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument(
        "--limit", type=int, default=0, help="Limit number of files to process with LLM"
    )
    parser.add_argument(
        "--resume", action="store_true", help="Resume from existing tasks.json"
    )
    args = parser.parse_args()
    generate_tasks(Path(args.scan), Path(args.out_dir), args.limit, args.resume)

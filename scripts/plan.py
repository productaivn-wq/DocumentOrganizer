#!/usr/bin/env python3
"""
plan.py — Task generation engine for DocumentOrganizer.

Reads scan.json (from scan.py), generates tasks.json with:
  - Duplicate dedup entries
  - Folder merge candidates
  - LLM-powered semantic clustering and routing
  - LLM-powered semantic rename

Filename format: PP.SSS - YYYYMMDD - Semantic_Title [TAG1][TAG2].ext
  PP  = Project number (from jd_registry)
  SSS = Auto-increment sequence per project
  TAG = Universal type tag (DS/DC/BD/VR/CM/AC/RF/AR/SY)
"""

import argparse
import concurrent.futures
import datetime
import json
import math
import re
from pathlib import Path

try:
    from .llm_generation import _llm_generate
except ImportError:
    from llm_generation import _llm_generate

import os as _os

HAS_LLM = bool(_os.environ.get("OPENAI_API_KEY", "").strip())

try:
    from pydantic import BaseModel, Field
except ImportError:
    pass

# Embedding support via ollama is optional — fallback to zero vectors
try:
    import ollama

    HAS_OLLAMA_EMBED = True
except ImportError:
    HAS_OLLAMA_EMBED = False

# HAS_OLLAMA kept for backward compat with compute_embedding only
HAS_OLLAMA = HAS_OLLAMA_EMBED

from jd_registry import (
    VALID_TAGS,
    discover_projects,
    extract_id,
    format_filename,
    load_registry,
    next_sequence,
    resolve_project,
    save_registry,
)
from logger import emit_progress

# ---------------------------------------------------------------------------
# Organizer artifact exclusion — these files are generated by previous
# DocumentOrganizer runs and should NEVER be fed to the LLM for renaming.
# ---------------------------------------------------------------------------
ORGANIZER_ARTIFACTS = {
    "dedup_log.md",
    "move_log.md",
    "rename_log.md",
    "tasks.json",
    "conflicts.md",
    "conflicts_summary.md",
    "dedup_log",
    "move_log",
    "rename_log",
    "_full_inventory.csv",
    "_scan.json",
    "scan.json",
    "progress.log",
}

ORGANIZER_ARTIFACT_PREFIXES = ("_scan_", "_full_inventory")


def _is_organizer_artifact(filepath: str) -> bool:
    """Return True if the file is a DocumentOrganizer-generated artifact."""
    name = Path(filepath).name
    if name in ORGANIZER_ARTIFACTS:
        return True
    stem = Path(filepath).stem
    for prefix in ORGANIZER_ARTIFACT_PREFIXES:
        if stem.startswith(prefix):
            return True
    return False


# ---------------------------------------------------------------------------
# LLM Data Models
# ---------------------------------------------------------------------------


class RenameSuggestion(BaseModel):
    suggested_title: str = Field(
        description="Short descriptive English title using underscores, no spaces"
    )


class FileRename(BaseModel):
    original_path: str = Field(description="The exact file path provided")
    suggested_title: str = Field(
        description="Short descriptive English title using underscores, no spaces"
    )


class BatchRenameSuggestion(BaseModel):
    renames: list[FileRename] = Field(description="List of suggested renames")


class ClusterRoutingSuggestion(BaseModel):
    suggested_folder: str = Field(
        description="Target folder name from the provided list for the entire cluster"
    )
    tags: list[str] = Field(
        description="1-2 type tags from: IN PL BU CH SH RE for the entire cluster"
    )


def _discover_existing_folders(target_root: str) -> list[str]:
    """Walk the target root (depth 1) to find existing subfolder names."""
    folders = []
    try:
        root = Path(target_root)
        for item in sorted(root.iterdir()):
            if item.is_dir() and not item.name.startswith("."):
                folders.append(item.name)
    except (OSError, PermissionError):
        pass
    return folders


def _build_folder_context(existing_folders: list[str] | None) -> str:
    if not existing_folders:
        return ""
    folder_list = "\n".join(f"  - {f}" for f in existing_folders)
    return f"""
EXISTING FOLDERS in this workspace (you MUST pick one of these):
{folder_list}

If the file truly does not fit any existing folder, use "99_SYSTEM" as fallback.
"""


# ---------------------------------------------------------------------------
# Tag and title validation
# ---------------------------------------------------------------------------


def _clean_title(title: str) -> str:
    """Clean an LLM-generated title into a safe filename component."""
    title = re.sub(r"[\s]+", "_", title)
    title = re.sub(r"[^A-Za-z0-9_-]", "", title)
    title = title.strip("_-") or "Untitled"
    return title


def _clean_tags(tags: list[str]) -> list[str]:
    """Filter tags to only valid ones. Max 2 tags."""
    return [t.upper() for t in tags if t.upper() in VALID_TAGS][:2]


def _build_tag_reference() -> str:
    lines = []
    for code, desc in VALID_TAGS.items():
        lines.append(f"  {code} = {desc}")
    return "\n".join(lines)


def _normalize_suggested_folder(folder: str, existing_folders: list[str] | None) -> str:
    folder = folder.replace("\\", "/")
    parts = [p for p in folder.split("/") if p.strip()]
    if not parts:
        return folder

    if existing_folders:
        for part in parts:
            if part in existing_folders:
                return part
    return parts[-1]


# ---------------------------------------------------------------------------
# Semantic Clustering & Atomic Extraction (MECE Upgrades)
# ---------------------------------------------------------------------------


def _cosine_similarity(v1: list[float], v2: list[float]) -> float:
    dot_product = sum(a * b for a, b in zip(v1, v2))
    magnitude1 = math.sqrt(sum(a * a for a in v1))
    magnitude2 = math.sqrt(sum(b * b for b in v2))
    if magnitude1 == 0 or magnitude2 == 0:
        return 0.0
    return dot_product / (magnitude1 * magnitude2)


def cluster_files(
    embeddings: dict[str, list[float]], threshold: float = 0.8
) -> list[list[str]]:
    clusters = []
    for filepath, emb in embeddings.items():
        placed = False
        for cluster in clusters:
            rep_file = cluster[0]
            sim = _cosine_similarity(emb, embeddings[rep_file])
            if sim >= threshold:
                cluster.append(filepath)
                placed = True
                break
        if not placed:
            clusters.append([filepath])
    return clusters



def generate_atomic_summary(content: str) -> str:
    if not HAS_LLM:
        return content[:500]
    res = _llm_generate(
        "Summarize the following document excerpt in one concise sentence.",
        content[:1500],
    )
    return res if res and not res.startswith("[ERROR]") else content[:500]


def compute_embedding(text: str) -> list[float]:
    if not HAS_OLLAMA_EMBED:
        return [0.0] * 384
    try:
        response = ollama.embeddings(model="all-minilm:latest", prompt=text)
        return response.get("embedding", [0.0] * 384)
    except Exception:
        return [0.0] * 384


def generate_cluster_routing_suggestion(
    cluster_summaries: list[str], existing_folders: list[str] | None = None
) -> dict:
    if not HAS_LLM:
        return {}
    folder_ctx = _build_folder_context(existing_folders)
    summaries_text = "\n".join(f"- {s}" for s in cluster_summaries)
    prompt = (
        f"Given {len(cluster_summaries)} related files:\n{summaries_text}\n\n"
        f"Existing folders:\n{folder_ctx}\n\n"
        "Return JSON with keys 'suggested_folder' and 'tags'."
    )
    try:
        raw = _llm_generate("You are a workspace file router.", prompt, json_mode=True)
        result = json.loads(raw)
        result["suggested_folder"] = _normalize_suggested_folder(
            result.get("suggested_folder", ""), existing_folders
        )
        result["tags"] = _clean_tags(result.get("tags", []))
        return result
    except Exception as e:
        emit_progress(
            "DocumentOrganizer", "PLAN", f"Error routing cluster: {e}", level="ERROR"
        )
        return {}


def generate_batch_title_suggestions(
    cluster: list[str], atomic_summaries: dict[str, str]
) -> dict[str, str]:
    if not HAS_LLM:
        return {fp: _clean_title(Path(fp).stem) for fp in cluster}

    file_list_str = "\n".join(
        f"- Path: {fp}\n  Summary: {atomic_summaries[fp]}" for fp in cluster
    )
    prompt = f"Suggest clean semantic filenames as JSON for:\n{file_list_str}"
    try:
        import json as _json

        raw = _llm_generate("You are a file naming assistant.", prompt, json_mode=True)
        result = _json.loads(raw)

        cleaned_titles = {}
        for rename in result.get("renames", []):
            cleaned_titles[rename["original_path"]] = _clean_title(
                rename["suggested_title"]
            )

        # Fallback for missing paths
        for fp in cluster:
            if fp not in cleaned_titles:
                cleaned_titles[fp] = _clean_title(Path(fp).stem)
        return cleaned_titles
    except Exception as e:
        emit_progress(
            "DocumentOrganizer", "PLAN", f"Error batch renaming: {e}", level="ERROR"
        )
        return {fp: _clean_title(Path(fp).stem) for fp in cluster}


